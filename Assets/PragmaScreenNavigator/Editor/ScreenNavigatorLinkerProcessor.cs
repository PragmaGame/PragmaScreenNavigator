using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security;
using System.Text;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEditor.Compilation;
using UnityEditor.UnityLinker;

namespace Pragma.ScreenNavigator
{
    /// <summary>
    /// Generates a link.xml for every player build that keeps every concrete view model whole, including the ones declared
    /// in user assemblies. View models are created through reflection (<see cref="IViewModelFactory"/> over a DI container or
    /// <see cref="ActivatorViewModelFactory"/>), so their constructors look unused to the linker, and Medium or High
    /// stripping removes them.
    /// </summary>
    internal sealed class ScreenNavigatorLinkerProcessor : IUnityLinkerProcessor
    {
        private const string OUTPUT_PATH = "Library/Pragma.ScreenNavigator/link.xml";

        public int callbackOrder => 0;

        public string GenerateAdditionalLinkXmlFile(BuildReport report, UnityLinkerBuildPipelineData data)
        {
            var path = Path.GetFullPath(OUTPUT_PATH);
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, GenerateLinkXml(FindPlayerViewModelTypes()));

            return path;
        }

        /// <summary>View model types of the assemblies that reach the player: editor code and tests never do.</summary>
        internal static IEnumerable<Type> FindPlayerViewModelTypes()
        {
            var editorAssemblies = CompilationPipeline.GetAssemblies(AssembliesType.Editor)
                .Select(assembly => assembly.name)
                .Except(CompilationPipeline.GetAssemblies(AssembliesType.Player).Select(assembly => assembly.name))
                .ToHashSet();

            return TypeCache.GetTypesDerivedFrom<ViewModel>()
                .Where(type => !editorAssemblies.Contains(type.Assembly.GetName().Name));
        }

        internal static string GenerateLinkXml(IEnumerable<Type> viewModelTypes)
        {
            // An abstract view model is kept through the constructors of the concrete ones.
            var assemblies = viewModelTypes
                .Where(type => !type.IsAbstract)
                .GroupBy(type => type.Assembly.GetName().Name)
                .OrderBy(assembly => assembly.Key, StringComparer.Ordinal);

            var xml = new StringBuilder();
            xml.AppendLine("<!-- Generated by Pragma.ScreenNavigator.ScreenNavigatorLinkerProcessor for the current build. -->");
            xml.AppendLine("<linker>");

            foreach (var assembly in assemblies)
            {
                // A precompiled plugin excluded from this platform is simply skipped.
                xml.AppendLine($"  <assembly fullname=\"{SecurityElement.Escape(assembly.Key)}\" ignoreIfMissing=\"1\">");

                foreach (var typeName in assembly.Select(GetLinkerName).Distinct().OrderBy(name => name, StringComparer.Ordinal))
                {
                    xml.AppendLine($"    <type fullname=\"{SecurityElement.Escape(typeName)}\" preserve=\"all\"/>");
                }

                xml.AppendLine("  </assembly>");
            }

            xml.AppendLine("</linker>");

            return xml.ToString();
        }

        // link.xml separates nested types with '/'; generic definitions keep their `N arity suffix, as in metadata.
        private static string GetLinkerName(Type type)
        {
            return type.FullName.Replace('+', '/');
        }
    }
}
